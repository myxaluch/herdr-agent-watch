#!/usr/bin/env bash
# Renders the hc templates from templates/*.md and config.json.
#
#   bash render-templates.sh            write to ~/.config/herdr-core/templates (or AW_TEMPLATES_OUT)
#
# hc reads templates only from its own folder and does not substitute anything, so every
# {{name}} is filled in here. A file <AW_DATA>/templates/<name>.md replaces the shipped one.
# An existing template that agent-watch did not write is never replaced.
set -uo pipefail

AW_HOME="${AW_HOME:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)}"
AW_DATA="${AW_DATA:-$HOME/.config/herdr-core/agent-watch}"
AW_CONFIG="${AW_CONFIG:-$AW_DATA/config.json}"
out="${AW_TEMPLATES_OUT:-$HOME/.config/herdr-core/templates}"
overrides="$(dirname "$AW_CONFIG")/templates"
marker="<!-- generated by agent-watch: edit config.json or the source template, then restart the watcher -->"

fail() { echo "render-templates: $*" >&2; exit 1; }

jq -e . "$AW_CONFIG" >/dev/null 2>&1 || fail "bad config $AW_CONFIG"

login=$(jq -r '.vars.github_login // empty' "$AW_CONFIG")
[ -n "$login" ] || login=$(gh api user --jq .login 2>/dev/null) || fail "no .vars.github_login and gh api user failed"

params=$(jq --arg home "$HOME" --arg login "$login" --arg notify "$AW_HOME/notify.sh" '
  def tilde: sub("^~/"; $home + "/") | gsub(" ~/"; " " + $home + "/");
  def repo_lines(f; fallback): [.vars.repos[]? | "- `\(.repo)`: \(f // fallback)"] | join("\n");
  def notes(k): (.vars.notes[k] // "") as $n | if $n == "" then "" else "## Extra instructions\n" + $n end;
  (.vars.reviews_dir // "~/.agent-watch/reviews" | tilde) as $reviews
  | "the repo'"'"'s agent instructions (`AGENTS.md`, `CLAUDE.md` or `.claude/CLAUDE.md`), the docs they name for the touched area, and its review guidelines when it has them" as $docs
  | "follow the repo'"'"'s own instructions for worktrees, tests, linters and commit messages" as $fix
  | [
      ["reviewer_command",   (.vars.agents.reviewer   // "claude --permission-mode auto --model opus --effort high" | tilde)],
      ["replies_command",    (.vars.agents.replies    // "claude --permission-mode auto --model sonnet" | tilde)],
      ["crosscheck_command", (.vars.agents.crosscheck // "codex --no-daemon -s workspace-write --add-dir {{reviews_dir}} -a never" | tilde)],
      ["reviews_dir",        $reviews],
      ["github_login",       $login],
      ["output_language",    (.vars.output_language  // "English")],
      ["comment_language",   (.vars.comment_language // "English")],
      ["cmd_fix",            (.vars.commands.fix     // "fix")],
      ["cmd_commit",         (.vars.commands.commit  // "commit")],
      ["cmd_reply",          (.vars.commands.reply   // "reply")],
      ["cmd_recheck",        (.vars.commands.recheck // "check new")],
      ["cmd_submit",         (.vars.commands.submit  // "submit")],
      ["repos_review",       repo_lines(.review_docs; $docs)],
      ["repos_replies",      repo_lines(.replies_docs // .review_docs; $docs)],
      ["repos_fix",          repo_lines(.fix_notes; $fix)],
      ["reviewer_notes",     notes("reviewer")],
      ["replies_notes",      notes("replies")],
      ["crosscheck_notes",   notes("crosscheck")],
      ["notify",             $notify]
    ]' "$AW_CONFIG") || fail "cannot read the template parameters from $AW_CONFIG"

mkdir -p "$out" || fail "cannot create $out"

rc=0
for src in "$AW_HOME"/templates/*.md; do
  name=$(basename "$src")
  [ -f "$overrides/$name" ] && src="$overrides/$name"
  dst="$out/$name"

  if [ -f "$dst" ] && ! grep -qF "$marker" "$dst"; then
    echo "render-templates: $dst exists and was not written by agent-watch, left as it is" >&2
    rc=1; continue
  fi

  text=$(jq -Rsr --argjson p "$params" \
    'reduce $p[] as $kv (.; split("{{" + $kv[0] + "}}") | join($kv[1])) | sub("\\s+$"; "")' "$src") \
    || { echo "render-templates: cannot render $src" >&2; rc=1; continue; }

  left=$(grep -o '{{[a-z_]*}}' <<<"$text" | sort -u | paste -sd' ' -)
  if [ -n "$left" ]; then
    echo "render-templates: $src has unknown parameters: $left" >&2
    rc=1; continue
  fi

  printf '%s\n\n%s\n' "$text" "$marker" > "$dst.tmp" && mv "$dst.tmp" "$dst" || { rc=1; continue; }
done
exit $rc
